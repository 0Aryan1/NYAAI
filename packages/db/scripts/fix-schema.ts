/**
 * Post-processes `drizzle-kit pull` output: drizzle-kit cannot map citext or tsvector and emits `unknown(...)`.
 * Replaces them with custom types and removes the throwaway SQL/meta files the pull writes.
 */
import { readFile, rm, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/schema');
const file = path.join(dir, 'schema.ts');
let src = await readFile(file, 'utf8');

src = src
  .replace(/\t\/\/ TODO: failed to parse database type '(citext|tsvector)'\n/g, '')
  .replace(/unknown\("email"\)/g, 'citext("email")')
  .replace(/unknown\("tsv"\)/g, 'tsvector("tsv")');
if (src.includes('unknown(')) throw new Error('schema.ts still has unmapped column types; extend fix-schema.ts');

const header = `import { customType } from "drizzle-orm/pg-core"
const citext = customType<{ data: string }>({ dataType: () => 'citext' })
const tsvector = customType<{ data: string }>({ dataType: () => 'tsvector' })
`;
if (!src.includes('const citext =')) src = src.replace(/(import \{ sql \} from "drizzle-orm"\n)/, `$1${header}`);
src = `// Generated by \`pnpm --filter @nyaai/db schema:pull\` from the live database. Do not edit by hand.\n${src}`;
await writeFile(file, src);

for (const entry of await readdir(dir)) {
  if (entry.endsWith('.sql') || entry === 'meta') await rm(path.join(dir, entry), { recursive: true, force: true });
}
console.log('schema.ts fixed');
